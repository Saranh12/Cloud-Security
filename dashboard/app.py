def is_safe_path(target_path):
    resolved = target_path.resolve()
    if any(str(resolved).startswith(str(d.resolve())) for d in ALLOWED_DIRS):
        return True
    if resolved.parent == BASE_DIR.resolve() and resolved.name.startswith("networkpolicy") and resolved.name.endswith(".yaml"):
        return True
    return False

def read_json_file(path):
    try:
        if path.exists():
            with open(path, "r", encoding="utf-8") as f:
                return json.load(f)
    except Exception as e:
        return {"error": str(e)}
    return {}

def read_text_file(path, max_lines=500):
    try:
        if path.exists():
            with open(path, "r", encoding="utf-8", errors="ignore") as f:
                lines = f.readlines()
                return "".join(lines[:max_lines])
    except Exception as e:
        return f"Error reading file: {e}"
    return ""

def get_real_alerts(limit=50):
    alerts = []
    if ALERTS_LOG_FILE.exists():
        try:
            with open(ALERTS_LOG_FILE, "r", encoding="utf-8", errors="ignore") as f:
                lines = [line.strip() for line in f if line.strip()]
                for line in reversed(lines):
                    try:
                        time_part = ""
                        module_part = "SYS"
                        severity_part = "INFO"
                        message_part = line

                        if line.startswith("[") and "]" in line:
                            time_part = line[1:line.find("]")]
                            rest = line[line.find("]")+1:].strip()
                            parts = [p.strip() for p in rest.split("|")]
                            for p in parts:
                                if p.startswith("MODULE="):
                                    module_part = p.replace("MODULE=", "").strip()
                                elif p.startswith("SEVERITY="):
                                    severity_part = p.replace("SEVERITY=", "").strip().upper()
                                    if severity_part in ["NONE", "NORMAL"]:
                                        severity_part = "INFO"
                                elif p.startswith("STATUS="):
                                    pass
                                else:
                                    message_part = p
                        alerts.append({
                            "time": time_part,
                            "module": module_part,
                            "severity": severity_part,
                            "message": message_part
                        })
                        if len(alerts) >= limit:
                            break
                    except Exception:
                        pass
        except Exception:
            pass
    return alerts

