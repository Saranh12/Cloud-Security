@app.route("/api/module/refresh", methods=["POST"])
def api_module_refresh():
    """
    Refreshes M4 and/or M5 with live telemetry queried from the Kubernetes cluster.
    Updates the shared state in dashboard_state.json and returns fresh telemetry.
    """
    from runtime_target import get_live_assessment_telemetry
    data = request.get_json(force=True, silent=True) or {}
    workload = data.get("workload_name") or request.args.get("workload_name")
    namespace = data.get("namespace") or request.args.get("namespace", "default")
    mod = (data.get("module") or "all").lower()

    telemetry = get_live_assessment_telemetry(workload_name=workload, namespace=namespace)

    # Synchronize state in STATE_FILE
    with _PIPELINE_LOCK:
        curr_state = read_json_file(STATE_FILE)
        if not curr_state:
            curr_state = {}
        if "modules" not in curr_state:
            curr_state["modules"] = {}

        # Update M4 details
        m4_tel = telemetry.get("m4", {})
        if m4_tel:
            curr_state["modules"]["M4"] = {
                "status": "COMPLETED" if m4_tel.get("status") in ["NORMAL", "THREAT DETECTED", "SUSPICIOUS ACTIVITY DETECTED"] else m4_tel.get("status", "UNAVAILABLE"),
                "severity": m4_tel.get("severity", "None"),
                "message": m4_tel.get("reason", ""),
                "details": m4_tel
            }
            curr_state["modules"]["m4"] = curr_state["modules"]["M4"]

        # Update M5 details
        m5_tel = telemetry.get("m5", {})
        if m5_tel:
            curr_state["modules"]["M5"] = {
                "status": "COMPLETED" if m5_tel.get("status") in ["NORMAL", "SUSPICIOUS ACTIVITY DETECTED"] else m5_tel.get("status", "UNAVAILABLE"),
                "severity": m5_tel.get("severity", "None"),
                "message": m5_tel.get("reason", ""),
                "details": m5_tel
            }
            curr_state["modules"]["m5"] = curr_state["modules"]["M5"]

        # Update deployment & target references
        curr_state["target_pod"] = telemetry.get("pod_name")
        curr_state["deployment_name"] = telemetry.get("workload_name")
        if "deployment" not in curr_state:
            curr_state["deployment"] = {}
        rt = telemetry.get("runtime_target", {})
        if rt:
            curr_state["deployment"].update({
                "workload_name": rt.get("workload_name"),
                "pod_name": rt.get("pod_name"),
                "container_name": rt.get("container_name"),
                "container_id": rt.get("container_id"),
                "runtime_image": rt.get("runtime_image"),
                "runtime_image_id": rt.get("image_id"),
                "privileged_effective": rt.get("privileged", False),
                "privileged_status": "ENABLED" if rt.get("privileged") else "DISABLED"
            })
            curr_state["runtime_target_obj"] = rt

        try:
            with open(STATE_FILE, "w", encoding="utf-8") as f:
                json.dump(curr_state, f, indent=4)
        except Exception:
            pass

    return jsonify({
        "success": True,
        "message": f"Successfully refreshed live Kubernetes telemetry for '{telemetry.get('workload_name')}'",
        "telemetry": telemetry
    })



