@app.route("/api/workload/privileged", methods=["POST"])
def api_workload_privileged():
    """
    Updates the securityContext.privileged profile on the running KubeGuard assessment workload.
    Applies the patch, waits for Kubernetes rollout, discovers the replacement pod,
    and updates the active state and M5 inspection results accordingly.
    """
    data = request.get_json(force=True, silent=True) or {}
    state = read_json_file(STATE_FILE)
    dep = state.get("deployment", {})

    workload_name = data.get("workload_name") or dep.get("workload_name") or state.get("deployment_name")
    namespace = data.get("namespace") or dep.get("namespace") or state.get("namespace") or "default"
    privileged_flag = data.get("privileged", True)
    if isinstance(privileged_flag, str):
        privileged_flag = (privileged_flag.lower() in ["true", "1", "yes", "enabled"])
    else:
        privileged_flag = bool(privileged_flag)

    if not workload_name:
        return jsonify({
            "success": False,
            "error": "No active workload available to update privileged mode."
        }), 400

    res = update_workload_privileged_mode(workload_name, namespace=namespace, privileged=privileged_flag)

    if res.get("success"):
        with _PIPELINE_LOCK:
            curr_state = read_json_file(STATE_FILE)
            if "deployment" not in curr_state:
                curr_state["deployment"] = {}

            curr_state["deployment"]["privileged_requested"] = res["privileged_requested"]
            curr_state["deployment"]["privileged_admitted"] = res["privileged_admitted"]
            curr_state["deployment"]["privileged_in_spec"] = res["privileged_in_spec"]
            curr_state["deployment"]["privileged_effective"] = res["privileged_effective"]
            curr_state["deployment"]["privileged_status"] = res["privileged_status"]
            curr_state["deployment"]["pod_name"] = res["pod_name"]
            curr_state["deployment"]["pod_uid"] = res.get("pod_uid")
            curr_state["deployment"]["container_id"] = res.get("container_id")
            curr_state["privileged_status"] = res["privileged_status"]
            curr_state["target_pod"] = res["pod_name"]

            if "runtime_target_obj" in curr_state and isinstance(curr_state["runtime_target_obj"], dict):
                curr_state["runtime_target_obj"]["pod_name"] = res["pod_name"]
                curr_state["runtime_target_obj"]["pod_uid"] = res.get("pod_uid")
                curr_state["runtime_target_obj"]["container_id"] = res.get("container_id")
                curr_state["runtime_target_obj"]["privileged"] = res["privileged_effective"]

            # Re-evaluate M5 escape indicators on the replacement pod
            try:
                from module5_escape import get_pods, detect_escape_indicators
                pod_data = get_pods(target_pod=res["pod_name"], namespace=namespace, preferred_workload=workload_name)
                m5_findings = detect_escape_indicators(pod_data, target_container=res.get("container_name"))
                if isinstance(m5_findings, list) and len(m5_findings) > 0:
                    primary_m5 = m5_findings[0]
                    is_escape = primary_m5.get("incident_triggered", False)
                    m5_status = "COMPLETED"
                    m5_sev = primary_m5.get("severity", "None")
                    m5_msg = f"Privileged container detected: {res['pod_name']}" if primary_m5.get("privileged") else f"Container security check passed: {res['pod_name']}"
                    m5_details = {
                        "pod": res["pod_name"],
                        "namespace": namespace,
                        "privileged": primary_m5.get("privileged", False),
                        "escape_detected": is_escape,
                        "incident_triggered": is_escape,
                        "severity": m5_sev,
                        "findings": primary_m5.get("findings", []),
                        "structured_findings": primary_m5.get("structured_findings", []),
                        "escape_items": m5_findings,
                        "last_assessed_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S")
                    }
                    if "modules" in curr_state and isinstance(curr_state["modules"], dict):
                        curr_state["modules"]["M5"] = {
                            "status": m5_status,
                            "severity": m5_sev,
                            "message": m5_msg,
                            "details": m5_details
                        }
            except Exception:
                pass

            try:
                with open(STATE_FILE, "w", encoding="utf-8") as f:
                    json.dump(curr_state, f, indent=4)
            except Exception:
                pass

    return jsonify(res)


