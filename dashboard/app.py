@app.route("/api/workload/select", methods=["POST"])
def api_workload_select():
    """
    Selects and persists the active target workload for all assessment modules.
    Resolves the live pod and container configuration immediately.
    """
    data = request.get_json(force=True, silent=True) or {}
    workload_name = data.get("workload_name") or request.form.get("workload_name")
    namespace = data.get("namespace") or request.form.get("namespace") or "default"

    if not workload_name:
        return jsonify({"success": False, "error": "workload_name is required"}), 400

    ok, target_obj, err = resolve_existing_deployment_target(workload_name, namespace=namespace)
    if not ok or not target_obj:
        return jsonify({"success": False, "error": err or "Failed to resolve workload"}), 404

    cfg = persist_target_config(
        workload_name=target_obj.workload_name,
        namespace=target_obj.namespace,
        container_name=target_obj.container_name,
        image=target_obj.runtime_image,
        workload_kind=target_obj.workload_kind
    )

    with _PIPELINE_LOCK:
        curr_state = read_json_file(STATE_FILE)
        curr_state["selected_image"] = target_obj.runtime_image
        curr_state["image"] = target_obj.runtime_image
        curr_state["deployment_name"] = target_obj.workload_name
        curr_state["target_pod"] = target_obj.pod_name
        curr_state["namespace"] = target_obj.namespace
        curr_state["privileged_status"] = "ENABLED" if target_obj.privileged else "DISABLED"
        curr_state["runtime_target_obj"] = target_obj.to_dict()
        if "deployment" not in curr_state:
            curr_state["deployment"] = {}
        curr_state["deployment"].update({
            "status": "RUNNING",
            "runtime_target": "kubernetes",
            "workload_name": target_obj.workload_name,
            "workload_kind": target_obj.workload_kind,
            "pod_name": target_obj.pod_name,
            "container_name": target_obj.container_name,
            "container_id": target_obj.container_id,
            "runtime_image": target_obj.runtime_image,
            "runtime_image_id": target_obj.image_id,
            "privileged_requested": target_obj.privileged,
            "privileged_effective": target_obj.privileged,
            "privileged_status": "ENABLED" if target_obj.privileged else "DISABLED"
        })
        try:
            with open(STATE_FILE, "w", encoding="utf-8") as f:
                json.dump(curr_state, f, indent=4)
        except Exception:
            pass

    return jsonify({
        "success": True,
        "message": f"Target workload set to '{target_obj.workload_name}'",
        "workload": target_obj.to_dict(),
        "config": cfg
    })


@app.route("/api/workload/cleanup", methods=["POST"])
def api_workload_cleanup():
    """
    Safely stops and removes only KubeGuard-managed deployment resources
    for the current session. Never deletes user workloads or system pods.
    """
    data = request.get_json(force=True, silent=True) or {}
