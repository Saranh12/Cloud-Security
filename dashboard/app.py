@app.route("/api/dashboard")
@app.route("/api/data")
def api_dashboard():
    """Returns the execution state generated by main.py, or a historical run if run_id is supplied."""
    req_run_id = request.args.get("run_id", "").strip()
    if req_run_id and req_run_id != "latest":
        try:
            from run_manager import get_run
            run_data = get_run(req_run_id)
            if run_data and isinstance(run_data, dict):
                if "modules" in run_data and isinstance(run_data["modules"], dict):
                    for k in list(run_data["modules"].keys()):
                        val = run_data["modules"][k]
                        run_data["modules"][k.upper()] = val
                        run_data["modules"][k.lower()] = val
                        run_data[k.upper()] = val
                        run_data[k.lower()] = val
                run_data["alerts"] = get_real_alerts(limit=50)
                m11_details = run_data.get("modules", {}).get("M11", {}).get("details", {})
                run_data["current_report"] = m11_details
                return jsonify(run_data)
        except Exception:
            pass

    state = read_json_file(STATE_FILE)

    # If state file does not exist yet or is empty, provide clean NOT RUN initial structure
    if not state or not isinstance(state, dict) or "modules" not in state:
        default_modules = {
            f"M{i}": {"status": "NOT RUN", "severity": "None", "message": "", "details": {}}
            for i in range(1, 12)
        }
        state = {
            "execution_time": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "modules": default_modules,
            "overview": {
                "overall_risk": "NOT RUN",
                "pods_monitored": 0,
                "suspicious_pods": 0,
                "vulnerabilities": 0,
                "vuln_breakdown": {"critical": 0, "high": 0, "medium": 0, "low": 0},
                "evidence_integrity": "NOT RUN",
                "forensic_reports_count": 0,
                "findings_distribution": {"total": 0, "critical": 0, "high": 0, "medium": 0, "low": 0}
            }
        }

    # Normalize modules dictionary so both uppercase (M1) and lowercase (m1) access work
    if "modules" in state and isinstance(state["modules"], dict):
        for k in list(state["modules"].keys()):
            val = state["modules"][k]
            state["modules"][k.upper()] = val
            state["modules"][k.lower()] = val
            state[k.upper()] = val
            state[k.lower()] = val

    # Attach real alerts log
    state["alerts"] = get_real_alerts(limit=50)

    # Attach current execution forensic report details if generated and verified
    m11_details = state.get("modules", {}).get("M11", {}).get("details", {})
    rep_path_str = m11_details.get("report_path")
    if rep_path_str:
        rep_p = (BASE_DIR / rep_path_str).resolve()
        if not rep_p.exists():
            rep_p = Path(rep_path_str).resolve()
        if rep_p.exists() and os.access(rep_p, os.R_OK):
            m11_details["report_verified"] = True
            m11_details["report_download_url"] = f"/download/reports/{rep_p.name}"
        else:
            m11_details["report_verified"] = False
    state["current_report"] = m11_details

    return jsonify(state)


@app.route("/api/report/download")
def api_report_download():
    """Verifies that the requested forensic report exists and is readable before serving download."""
    req_run_id = request.args.get("run_id", "").strip()
    report_file = None
    if req_run_id and req_run_id != "latest":
        try:
            from run_manager import get_run
            run_data = get_run(req_run_id)
            if run_data:
                rep_path = run_data.get("report_location") or run_data.get("modules", {}).get("M11", {}).get("details", {}).get("report_path")
                if rep_path:
                    p = Path(rep_path)
                    report_file = (BASE_DIR / p).resolve() if not p.is_absolute() else p.resolve()
        except Exception:
            pass
        if not report_file or not report_file.exists():
            cand1 = (REPORTS_DIR / f"KubeGuard_Forensic_Incident_Report_{req_run_id}.pdf").resolve()
            if cand1.exists():
                report_file = cand1
            else:
                cand2 = (REPORTS_DIR / f"forensic_report_{req_run_id}.pdf").resolve()
                if cand2.exists():
                    report_file = cand2
        if not report_file or not is_safe_path(report_file) or not report_file.exists() or not os.access(report_file, os.R_OK):
            abort(404)
    else:
        state = read_json_file(STATE_FILE)
        rep_path = state.get("modules", {}).get("M11", {}).get("details", {}).get("report_path")
        if rep_path:
            p = Path(rep_path)
            report_file = (BASE_DIR / p).resolve() if not p.is_absolute() else p.resolve()
        if not report_file or not report_file.exists():
            candidates = list(REPORTS_DIR.glob("KubeGuard_Forensic_Incident_Report_*.pdf")) + list(REPORTS_DIR.glob("forensic_report_*.pdf"))
            if candidates:
                candidates.sort(key=lambda x: x.stat().st_mtime, reverse=True)
                report_file = candidates[0].resolve()
        if not report_file or not is_safe_path(report_file) or not report_file.exists() or not os.access(report_file, os.R_OK):
            abort(404)

    return send_file(report_file, as_attachment=True, download_name=report_file.name)

