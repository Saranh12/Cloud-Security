@app.route("/api/pipeline/run", methods=["POST"])
@app.route("/api/run", methods=["POST"])
def api_run_pipeline():
    """
    Triggers the KubeGuard security pipeline for a selected container image.
    Accepts JSON: {"image": "...", "deploy": true/false} or form data.
    Never silently substitutes another image on invalid or empty input.
    """
    data = request.get_json(force=True, silent=True) or {}
    raw_image = data.get("image")
    if raw_image is None:
        raw_image = request.form.get("image")

    if raw_image is None or not str(raw_image).strip():
        return jsonify({
            "status": "FAILED",
            "error": "Container image reference cannot be empty. Please enter an image name (e.g., nginx:latest, python:3.12-slim)."
        }), 400

    deploy_flag = data.get("deploy", True)
    if isinstance(deploy_flag, str):
        deploy_flag = (deploy_flag.lower() in ["true", "1", "yes"])
    else:
        deploy_flag = bool(deploy_flag)

    image = str(raw_image).strip()

    # Deployment options
    deployment_target = str(data.get("deployment_target") or request.form.get("deployment_target") or "kubernetes").lower().strip()
    namespace = str(data.get("namespace") or request.form.get("namespace") or "default").strip()
    workload_name = str(data.get("workload_name") or request.form.get("workload_name") or "").strip()
    security_profile = str(data.get("security_profile") or request.form.get("security_profile") or "standard").lower().strip()
    port_mapping = str(data.get("port_mapping") or request.form.get("port_mapping") or "").strip()
    cpu_limit = str(data.get("cpu_limit") or request.form.get("cpu_limit") or "200m").strip()
    memory_limit = str(data.get("memory_limit") or request.form.get("memory_limit") or "128Mi").strip()
    env_vars = data.get("env_vars") or request.form.get("env_vars") or {}
    custom_capabilities = data.get("custom_capabilities") or request.form.get("custom_capabilities") or []

    # Validate image reference syntax using vuln_scan.validate_image_reference
    try:
        from vuln_scan import validate_image_reference
        is_valid, validation_msg = validate_image_reference(image)
        if not is_valid:
            return jsonify({
                "status": "FAILED",
                "error": validation_msg
            }), 400
        image = validation_msg
    except Exception as ve:
        return jsonify({
            "status": "FAILED",
            "error": f"Image validation error: {str(ve)}"
        }), 400

    with _PIPELINE_LOCK:
        state_data = read_json_file(STATE_FILE)
        is_state_running = (state_data.get("pipeline_status") == "RUNNING" or (state_data.get("status") == "RUNNING" and state_data.get("pipeline_status") not in ["COMPLETED", "FAILED"]))
        if _PIPELINE_STATE["running"] or is_state_running:
            active_img = _PIPELINE_STATE.get("image") or state_data.get("selected_image")
            active_rid = _PIPELINE_STATE.get("run_id") or state_data.get("run_id")
            return jsonify({
                "status": "ALREADY_RUNNING",
                "message": f"A security scan is already in progress for '{active_img}' (Run ID: {active_rid})",
                "image": active_img,
                "run_id": active_rid
            }), 409

        run_id = f"run_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
        _PIPELINE_STATE["running"] = True
        _PIPELINE_STATE["image"] = image
        _PIPELINE_STATE["run_id"] = run_id
        _PIPELINE_STATE["start_time"] = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        _PIPELINE_STATE["error"] = None

    def _execute():
        try:
            from main import run_pipeline
            run_pipeline(
                selected_image=image,
                run_id=run_id,
                is_cli=False,
                deploy_workload=deploy_flag,
                privileged=(security_profile == "privileged"),
                deployment_target=deployment_target,
                namespace=namespace,
                workload_name=workload_name,
                security_profile=security_profile,
                port_mapping=port_mapping,
                cpu_limit=cpu_limit,
                memory_limit=memory_limit,
                env_vars=env_vars,
                custom_capabilities=custom_capabilities
            )
        except Exception as e:
            with _PIPELINE_LOCK:
                _PIPELINE_STATE["error"] = str(e)
        finally:
            with _PIPELINE_LOCK:
                _PIPELINE_STATE["running"] = False

    thread = threading.Thread(target=_execute, daemon=True)
    thread.start()

    return jsonify({
        "status": "RUNNING",
        "message": f"Security scan started for '{image}'",
        "image": image,
        "run_id": run_id
    })


